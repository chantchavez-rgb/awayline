type Row = Record<string, unknown>;

type Sql = {
  get(statement: string, ...params: unknown[]): Promise<Row | undefined>;
  run(statement: string, ...params: unknown[]): Promise<void>;
};

type Queryable = {
  query(statement: string, params?: unknown[]): Promise<{ rows: Row[] }>;
};

const SQLITE_SCHEMA = `
  CREATE TABLE IF NOT EXISTS users (
    phone TEXT PRIMARY KEY,
    name TEXT NOT NULL DEFAULT '',
    token TEXT NOT NULL UNIQUE,
    created_at TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 0,
    reason TEXT NOT NULL DEFAULT 'busy',
    note TEXT NOT NULL DEFAULT '',
    until TEXT,
    time_zone TEXT NOT NULL DEFAULT 'UTC',
    cooldown_minutes INTEGER NOT NULL DEFAULT 360,
    updated_at TEXT
  );
  CREATE TABLE IF NOT EXISTS codes (
    phone TEXT PRIMARY KEY,
    code_hash TEXT NOT NULL,
    expires_at INTEGER NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0
  );
  CREATE TABLE IF NOT EXISTS code_limits (
    phone TEXT PRIMARY KEY,
    window_start INTEGER NOT NULL,
    count INTEGER NOT NULL
  );
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    phone TEXT NOT NULL,
    expires_at INTEGER NOT NULL
  );
  CREATE TABLE IF NOT EXISTS replies (
    phone TEXT NOT NULL,
    sender TEXT NOT NULL,
    sent_at INTEGER NOT NULL,
    PRIMARY KEY (phone, sender)
  );
  CREATE TABLE IF NOT EXISTS reply_log (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    phone TEXT NOT NULL,
    sent_at INTEGER NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_reply_log ON reply_log (phone, sent_at);
`;

